package com.zhmu100.ma.domain.model.device

/**
 * Статусы, в которых может находиться устройство.
 *
 * @property description Описание текущего состояния устройства
 */
enum class DeviceStatus(val description: String) {
    /**
     * Устройство включено и готово к использованию.
     */
    ON("Включено"),

    /**
     * Устройство выключено.
     */
    OFF("Выключено"),

    /**
     * Устройство находится в процессе подключения.
     */
    CONNECTING("Подключается")
}