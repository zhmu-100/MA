package com.zhmu100.ma.domain.model.device

/**
 * Типы устройств, доступные в системе.
 *
 * @property typeName Человеко-читаемое название типа устройства
 */
enum class DeviceType(val typeName: String) {
    /**
     * Умные часы — отслеживают здоровье, активность, пульс и т.д.
     */
    WATCH("Часы"),

    /**
     * Умные весы — измеряют массу тела, ИМТ, мышечную массу и другую информацию
     */
    SCALE("Весы")
}